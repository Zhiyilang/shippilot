def pin_dependencies(root, f, ctx):
    path = os.path.join(root, f.get("path") or "requirements.txt")
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    out, pinned, unknown = [], [], []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "==" in stripped:
            out.append(line)
            continue
        name = re.split(r"[<>=!\[; ]", stripped)[0].strip().lower()
        ver = stages.KNOWN_PINS.get(name)
        if ver:
            out.append("%s==%s" % (name, ver))
            pinned.append(name)
        else:
            out.append(line)
            unknown.append(name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    note = {"path": rel(root, path), "action": "updated", "pinned": pinned}
    if unknown:
        note["unpinned_unknown"] = unknown
    return [note]


def write_sbom(root, f, ctx):
    comps = []
    for name in ("requirements.txt",):
        p = os.path.join(root, name)
        if os.path.exists(p):
            with open(p, "r", encoding="utf-8") as fh:
                for line in fh:
                    s = line.strip()
                    if not s or s.startswith("#"):
                        continue
                    if "==" in s:
                        n, v = s.split("==", 1)
                    else:
                        n, v = re.split(r"[<>=!\[; ]", s)[0], "unknown"
                    comps.append({"type": "library", "name": n.strip(), "version": v.strip()})
    doc = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {"component": {"type": "application", "name": _repo_name(root)}},
        "components": comps,
    }
    return [_write(root, "sbom.json", json.dumps(doc, indent=2) + "\n")]


