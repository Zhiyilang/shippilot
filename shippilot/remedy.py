def applicable(f):
    """A fix is applicable only when the finding names one we actually own."""
    return bool(f.get("fix")) and f["fix"] in FIXERS


def apply(root, f, ctx=None):
    fn = FIXERS.get(f.get("fix"))
    if fn is None:
        return []
    return fn(root, f, ctx or {})
