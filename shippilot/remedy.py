def write_env_example(root, f, ctx):
    used = list(ctx.get("env_used") or [])
    declared = list(ctx.get("env_declared") or [])
    path = os.path.join(root, ".env.example")
    existing = ""
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            existing = fh.read()
    add = [v for v in used if v not in declared and v + "=" not in existing]
    body = existing.rstrip("\n")
    if add:
        body += "\n\n# Added by ShipPilot - read from source, never guessed\n"
        body += "".join("%s=\n" % v for v in add)
    return [_write(root, ".env.example", body.lstrip("\n") + "\n", action="updated")]


