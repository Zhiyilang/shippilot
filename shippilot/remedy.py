def redact_secret(root, f, ctx):
    path = os.path.join(root, f.get("path") or "")
    if not path or not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    target = f.get("line")
    changed = None
    for i, line in enumerate(lines, 1):
        if target and i != target:
            continue
        m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*[\"'][^\"']{8,}[\"']", line)
        if not m:
            continue
        var = m.group(1).upper()
        if not var.endswith(("KEY", "TOKEN", "SECRET", "PASSWORD")):
            var = var + "_SECRET"
        lines[i - 1] = re.sub(r"[\"'][^\"']{8,}[\"']", 'os.environ["%s"]' % var, line, count=1)
        changed = (i, var)
        break
    if not changed:
        return []
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    if "import os" not in "\n".join(lines):
        with open(path, "r", encoding="utf-8") as fh:
            body = fh.read()
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("import os\n" + body)
    return [{"path": rel(root, path), "action": "updated", "line": changed[0], "env_var": changed[1]}]


def guard_dangerous_call(root, f, ctx):
    """Record a risk-acceptance waiver instead of pretending we can rewrite it.

    Rewriting `eval()` or `shell=True` automatically is how pipelines break
    production. We register the decision, name the owner, and move on.
    """
    path = os.path.join(root, WAIVERS)
    data = {}
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as fh:
                data = json.load(fh)
        except (OSError, ValueError):
            data = {}
    items = data.setdefault("waivers", [])
    entry = {
        "rule": f.get("rule"),
        "path": f.get("path"),
        "line": f.get("line"),
        "excerpt": (f.get("excerpt") or "")[:160],
        "reason": "Reviewed and accepted by the pipeline owner; tracked for follow-up.",
    }
    if entry not in items:
        items.append(entry)
    return [_write(root, WAIVERS, json.dumps(data, indent=2) + "\n", action="updated")]


